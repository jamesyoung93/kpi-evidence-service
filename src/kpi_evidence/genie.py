from __future__ import annotations

import re
import time
from dataclasses import dataclass, field
from typing import Any, Callable

from .settings import Settings

TERMINAL_STATES = frozenset({"COMPLETED", "FAILED", "CANCELLED", "QUERY_RESULT_EXPIRED"})
DRAFT_NOTE = "Draft only - re-run read-only and route to the registry owner"
CONSUMER_NOTE = "Answer generated by Genie from published results; check the status and evidence columns"
MAX_QUESTION_CHARS = 4000
_SPACE_ID = re.compile(r"^[A-Za-z0-9_-]{1,64}$")
_WRITE_KEYWORDS = re.compile(
    r"\b(insert|update|delete|merge|drop|create|alter|truncate|grant|revoke|optimize|vacuum|restore|msck)\b", re.I)


@dataclass
class GenieAnswer:
    text: str | None
    sql: str | None
    rows: list[dict] | None
    conversation_id: str | None
    message_id: str | None
    status: str
    error: str | None
    note: str | None = None
    space_id: str | None = None
    question: str | None = None
    sql_description: str | None = None
    read_only: bool | None = None
    truncated: bool = False
    context: dict[str, Any] = field(default_factory=dict)

    @property
    def ok(self) -> bool:
        return self.status == "COMPLETED" and self.error is None


def _clean(text: Any, limit: int) -> str:
    t = re.sub(r"[\x00-\x08\x0b-\x1f\x7f]", " ", str(text or ""))
    t = re.sub(r"[ \t]+", " ", t).strip()
    return t[:limit]


def _status_name(status: Any) -> str:
    return str(getattr(status, "value", status) or "").upper()


def sql_is_read_only(sql: str | None) -> bool | None:
    """Conservative static check: one SELECT/WITH statement and no write or DDL keyword outside strings."""
    if not sql or not sql.strip():
        return None
    text = re.sub(r"--[^\n]*|/\*.*?\*/", " ", sql, flags=re.S)
    text = re.sub(r"'(?:[^'\\]|\\.|'')*'", "''", text)
    text = text.strip().rstrip(";").strip()
    if ";" in text or not re.match(r"^\(*\s*(select|with)\b", text, re.I):
        return False
    return _WRITE_KEYWORDS.search(text) is None


class GenieClient:
    """Thin wrapper over ``WorkspaceClient().genie`` (pass ``client`` for OBO or tests)."""

    def __init__(self, settings: Settings, client: Any = None, *, timeout_s: float = 600.0, min_poll_s: float = 1.0,
                 max_poll_s: float = 5.0, max_rows: int = 1000, delete_conversations: bool = True,
                 max_poll_errors: int = 3, sleep: Callable[[float], None] = time.sleep,
                 clock: Callable[[], float] = time.monotonic):
        self.settings = settings
        self._client = client
        self.timeout_s = float(timeout_s)
        self.min_poll_s = float(min_poll_s)
        self.max_poll_s = float(max_poll_s)
        self.max_rows = int(max_rows)
        self.delete_conversations = delete_conversations
        self.max_poll_errors = int(max_poll_errors)
        self._sleep = sleep
        self._clock = clock

    @property
    def client(self) -> Any:
        if self._client is None:
            from databricks.sdk import WorkspaceClient

            self._client = WorkspaceClient()
        return self._client

    def ask(self, question: str, space_id: str | None = None) -> GenieAnswer:
        """Ask the consumer Genie agent (``settings.genie_space_id``) about published results."""
        space = space_id or self.settings.genie_space_id
        answer = self._converse(space, _clean(question, MAX_QUESTION_CHARS), fetch_rows=True,
                                missing="settings.genie_space_id is not set")
        answer.note = CONSUMER_NOTE
        return answer

    def draft_sql(self, kpi_label: str, definition: str, report_value: float | None = None,
                  period_label: str | None = None, scope_text: str | None = None) -> GenieAnswer:
        """Ask the drafting agent (``settings.genie_drafting_space_id``) for candidate KPI SQL."""
        question = draft_question(kpi_label, definition, period_label, scope_text)
        answer = self._converse(self.settings.genie_drafting_space_id, question, fetch_rows=False,
                                missing="settings.genie_drafting_space_id is not set")
        answer.note = DRAFT_NOTE
        answer.rows = None
        answer.read_only = sql_is_read_only(answer.sql)
        answer.context = {"kpi_label": kpi_label, "definition": definition, "report_value": report_value,
                          "period_label": period_label, "scope_text": scope_text}
        return answer

    def draft_sql_for(self, kpi: Any, observation: Any) -> GenieAnswer:
        """``draft_sql`` from a registry ``KpiDefinition`` and an ``Observation``."""
        scope = getattr(observation, "scope", None) or {}
        scope_text = ", ".join(f"{k} = {v}" for k, v in sorted(scope.items())) if scope else "brand total"
        brand = getattr(observation, "brand", None)
        if brand:
            scope_text = f"brand {brand}; {scope_text}"
        return self.draft_sql(getattr(kpi, "label", str(kpi)), getattr(kpi, "definition", ""),
                              getattr(observation, "value", None), getattr(observation, "period_label", None),
                              scope_text)

    def _converse(self, space_id: str | None, content: str, *, fetch_rows: bool, missing: str) -> GenieAnswer:
        base = dict(text=None, sql=None, rows=None, conversation_id=None, message_id=None, space_id=space_id,
                    question=content)
        if not space_id:
            return GenieAnswer(**base, status="NOT_CONFIGURED", error=missing)
        if not _SPACE_ID.match(str(space_id)):
            return GenieAnswer(**base, status="ERROR", error=f"invalid Genie space id {space_id!r}")
        if not content:
            return GenieAnswer(**base, status="ERROR", error="empty question")
        try:
            genie = self.client.genie
            started = genie.start_conversation(space_id=space_id, content=content)
            conversation_id, message_id = _start_ids(started)
        except Exception as exc:
            return GenieAnswer(**base, status="ERROR", error=f"start_conversation failed: {type(exc).__name__}: {exc}")
        base.update(conversation_id=conversation_id, message_id=message_id)
        try:
            message, status, error = self._poll(genie, space_id, conversation_id, message_id)
            answer = GenieAnswer(**base, status=status, error=error)
            if message is not None:
                self._read_attachments(genie, answer, message, fetch_rows=fetch_rows and status == "COMPLETED")
            return answer
        finally:
            self._delete(genie, space_id, conversation_id)

    def _poll(self, genie: Any, space_id: str, conversation_id: str, message_id: str) -> tuple[Any, str, str | None]:
        deadline = self._clock() + self.timeout_s
        interval = self.min_poll_s
        message, failures = None, 0
        while True:
            try:
                message = genie.get_message(space_id=space_id, conversation_id=conversation_id, message_id=message_id)
                failures = 0
                status = _status_name(getattr(message, "status", None))
                if status in TERMINAL_STATES:
                    return message, status, _message_error(message, status)
            except Exception as exc:
                failures += 1
                if failures >= self.max_poll_errors:
                    return message, "ERROR", f"get_message failed {failures} times: {type(exc).__name__}: {exc}"
            remaining = deadline - self._clock()
            if remaining <= 0:
                return message, "TIMEOUT", f"no terminal state within {self.timeout_s:.0f} s"
            self._sleep(min(interval, remaining))
            interval = min(interval * 2, self.max_poll_s)

    def _read_attachments(self, genie: Any, answer: GenieAnswer, message: Any, *, fetch_rows: bool) -> None:
        texts = []
        for att in getattr(message, "attachments", None) or []:
            text_att = getattr(att, "text", None)
            if text_att is not None and getattr(text_att, "content", None):
                texts.append(str(text_att.content))
            query = getattr(att, "query", None)
            if query is not None and getattr(query, "query", None) and answer.sql is None:
                answer.sql = str(query.query)
                answer.sql_description = getattr(query, "description", None)
                if fetch_rows and getattr(att, "attachment_id", None):
                    self._fetch_rows(genie, answer, att.attachment_id)
        answer.text = "\n\n".join(texts) or None

    def _fetch_rows(self, genie: Any, answer: GenieAnswer, attachment_id: str) -> None:
        try:
            res = genie.get_message_attachment_query_result(
                space_id=answer.space_id, conversation_id=answer.conversation_id, message_id=answer.message_id,
                attachment_id=attachment_id)
        except Exception as exc:
            answer.error = f"query result unavailable: {type(exc).__name__}: {exc}"
            return
        rows, truncated = statement_rows(getattr(res, "statement_response", None), self.max_rows)
        answer.rows, answer.truncated = rows, truncated

    def _delete(self, genie: Any, space_id: str, conversation_id: str | None) -> None:
        if not (self.delete_conversations and conversation_id):
            return
        delete = getattr(genie, "delete_conversation", None)
        if delete is None:
            return
        try:
            delete(space_id=space_id, conversation_id=conversation_id)
        except Exception:
            pass


def _start_ids(started: Any) -> tuple[str, str]:
    for source in (started, getattr(started, "response", None)):
        if source is None:
            continue
        try:
            conversation_id, message_id = getattr(source, "conversation_id", None), getattr(source, "message_id", None)
        except Exception:
            continue
        if conversation_id and message_id:
            return str(conversation_id), str(message_id)
    raise ValueError("start_conversation returned no conversation_id/message_id")


def _message_error(message: Any, status: str) -> str | None:
    if status == "COMPLETED":
        return None
    err = getattr(message, "error", None)
    if err is not None:
        detail = getattr(err, "error", None) or str(err)
        kind = getattr(err, "type", None)
        kind = getattr(kind, "value", kind)
        return f"{kind}: {detail}" if kind else str(detail)
    return f"Genie message ended with status {status}"


def statement_rows(statement_response: Any, max_rows: int) -> tuple[list[dict] | None, bool]:
    """Rows as dicts from a ``StatementResponse`` (manifest schema + inline data_array)."""
    if statement_response is None:
        return None, False
    manifest = getattr(statement_response, "manifest", None)
    schema = getattr(manifest, "schema", None)
    columns = [str(getattr(c, "name", f"col_{i}")) for i, c in enumerate(getattr(schema, "columns", None) or [])]
    result = getattr(statement_response, "result", None)
    data = list(getattr(result, "data_array", None) or [])
    truncated = bool(getattr(manifest, "truncated", False)) or len(data) > max_rows \
        or getattr(result, "next_chunk_index", None) is not None
    rows = [dict(zip(columns or [f"col_{i}" for i in range(len(r))], r)) for r in data[:max_rows]]
    return rows, truncated


def draft_question(kpi_label: str, definition: str, period_label: str | None, scope_text: str | None) -> str:
    """The templated drafting question (definition first; no report value)."""
    return _clean(
        "Draft one read-only SQL query for a KPI that has no governed platform definition yet.\n"
        f"KPI: {_clean(kpi_label, 200)}\n"
        f"Definition: {_clean(definition, 1500)}\n"
        f"Period: {_clean(period_label, 100) or 'latest complete month'}\n"
        f"Scope: {_clean(scope_text, 300) or 'brand total'}\n"
        "Return a single SELECT that produces one row with one column named value, using only the curated "
        "tables in this space. Follow the definition exactly; do not modify data.", MAX_QUESTION_CHARS)
