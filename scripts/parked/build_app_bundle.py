"""PARKED (2026-10-19) - build the wheels the Databricks App installs and assemble its requirements file."""
from __future__ import annotations

import argparse
import hashlib
import re
import shutil
import subprocess
import sys
import tempfile
from collections.abc import Callable, Sequence
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
APP_DIR = ROOT / "apps" / "insight_harness"
VENDOR_DIRNAME = "vendor_wheels"
GENERATED = "requirements-databricks.txt"
UPSTREAM_COPY = "requirements-upstream.txt"
MARKER = "# Generated by scripts/parked/build_app_bundle.py"

PINS: dict[str, str] = {
    "streamlit": "streamlit==1.59.1",
    "pandas": "pandas==3.0.3",
    "altair": "altair==6.2.2",
    "databricks-sdk": "databricks-sdk>=0.72",
    "python-pptx": "python-pptx>=1.0,<2",
}
OPTIONAL_PINS: dict[str, str] = {"mlflow-skinny": "mlflow-skinny>=3.4"}

PROJECTS: tuple[tuple[str, str], ...] = (("reconloop", "libs/reconloop"), ("kpi_evidence", "."))

_NAME = re.compile(r"^\s*([A-Za-z0-9][A-Za-z0-9._-]*)")

Runner = Callable[[Sequence[str]], None]


class BuildError(RuntimeError):
    """A wheel build failed or produced an unexpected number of wheels."""


def canonical_name(name: str) -> str:
    """PEP 503 normalized project name."""
    return re.sub(r"[-_.]+", "-", name).lower()


def requirement_name(line: str) -> str | None:
    """Project name of a requirement line, or None for blanks, comments, options and paths."""
    text = line.split("#", 1)[0].strip()
    if not text or text.startswith(("-", ".", "/")) or "://" in text:
        return None
    match = _NAME.match(text)
    return canonical_name(match.group(1)) if match else None


def requirement_lines(text: str) -> list[str]:
    """Requirement lines without comments and blanks (inline comments stripped)."""
    out = []
    for raw in text.splitlines():
        line = raw.split("#", 1)[0].strip()
        if line:
            out.append(line)
    return out


def compose_requirements(upstream: Sequence[str], wheel_files: Sequence[str], *, with_mlflow: bool = False,
                         wheel_hashes: dict[str, str] | None = None) -> list[str]:
    """Upstream requirements with our PINS replacing their ranges, then the local wheels (last)."""
    pins = dict(PINS, **(OPTIONAL_PINS if with_mlflow else {}))
    pinned = {canonical_name(k) for k in pins}
    out: list[str] = [MARKER + " - do not edit. Upstream file: " + UPSTREAM_COPY + "."]
    seen: set[str] = set()
    for line in requirement_lines("\n".join(upstream)):
        name = requirement_name(line)
        if name is None:
            out.append(line)
            continue
        if name in pinned or name in seen:
            continue
        seen.add(name)
        out.append(line)
    out.extend(pins.values())
    for wheel in wheel_files:
        digest = (wheel_hashes or {}).get(wheel)
        if digest:
            out.append(f"# {wheel} sha256={digest}")
        out.append(f"./{VENDOR_DIRNAME}/{wheel}")
    return out


def _run(cmd: Sequence[str]) -> None:
    subprocess.run(list(cmd), check=True)


def build_command(project_dir: Path, out_dir: Path) -> list[str]:
    """uv when available (what the bundle artifacts use), else pip wheel without dependencies."""
    if shutil.which("uv"):
        return ["uv", "build", "--wheel", "--out-dir", str(out_dir), str(project_dir)]
    return [sys.executable, "-m", "pip", "wheel", "--no-deps", "-w", str(out_dir), str(project_dir)]


def build_wheel(project_dir: Path, dist_name: str, vendor_dir: Path, runner: Runner = _run) -> Path:
    """Build one wheel in a fresh temporary folder and move it into ``vendor_dir``."""
    build_debris = project_dir / "build"
    had_build_dir = build_debris.exists()
    with tempfile.TemporaryDirectory(prefix="kpi_app_wheel_") as tmp:
        out_dir = Path(tmp)
        try:
            runner(build_command(project_dir, out_dir))
        except (subprocess.CalledProcessError, OSError) as exc:
            raise BuildError(f"building {dist_name} in {project_dir} failed: {exc}") from exc
        finally:
            if not had_build_dir and build_debris.is_dir():
                shutil.rmtree(build_debris, ignore_errors=True)
        wheels = sorted(out_dir.glob(f"{dist_name}-*.whl"))
        if len(wheels) != 1:
            raise BuildError(f"expected one {dist_name} wheel from {project_dir}, found {[w.name for w in wheels]}")
        target = vendor_dir / wheels[0].name
        shutil.move(str(wheels[0]), target)
        return target


def build_all(root: Path, vendor_dir: Path, runner: Runner = _run) -> list[Path]:
    """Rebuild every vendored wheel; stale wheels are removed first so pip never sees two versions."""
    vendor_dir.mkdir(parents=True, exist_ok=True)
    for old in vendor_dir.glob("*.whl"):
        old.unlink()
    return [build_wheel((root / rel).resolve(), name, vendor_dir, runner) for name, rel in PROJECTS]


def sha256_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def upstream_requirements(app_dir: Path) -> str:
    """The upstream requirements text: the preserved copy if present, else requirements.txt."""
    copy = app_dir / UPSTREAM_COPY
    if copy.exists():
        return copy.read_text(encoding="utf-8")
    current = app_dir / "requirements.txt"
    text = current.read_text(encoding="utf-8")
    if text.startswith(MARKER):
        raise BuildError(f"{current} is a generated file but {copy.name} is missing; "
                         "restore the upstream file (git checkout) and run again")
    return text


def write_generated(app_dir: Path, lines: Sequence[str]) -> Path:
    path = app_dir / GENERATED
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def install_requirements(app_dir: Path) -> Path:
    """Make the generated file the App's requirements.txt, preserving the upstream file once."""
    generated = app_dir / GENERATED
    if not generated.exists():
        raise BuildError(f"{generated} does not exist; build first")
    current = app_dir / "requirements.txt"
    copy = app_dir / UPSTREAM_COPY
    if not copy.exists():
        upstream_requirements(app_dir)
        shutil.copyfile(current, copy)
    shutil.copyfile(generated, current)
    return current


def restore_requirements(app_dir: Path) -> bool:
    """Put the upstream requirements.txt back."""
    copy = app_dir / UPSTREAM_COPY
    if not copy.exists():
        return False
    shutil.copyfile(copy, app_dir / "requirements.txt")
    copy.unlink()
    return True


def main(argv: Sequence[str] | None = None, *, runner: Runner = _run) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--root", type=Path, default=ROOT, help="project root (contains pyproject.toml)")
    parser.add_argument("--install", action="store_true", help="install the generated file as requirements.txt")
    parser.add_argument("--restore", action="store_true", help="restore the upstream requirements.txt and exit")
    parser.add_argument("--skip-build", action="store_true", help="reuse the wheels already in vendor_wheels/")
    parser.add_argument("--with-mlflow", action="store_true", help="also pin mlflow-skinny>=3.4 (tracing in the app)")
    args = parser.parse_args(argv)

    root = args.root.resolve()
    app_dir = root / "apps" / "insight_harness"
    vendor_dir = app_dir / VENDOR_DIRNAME
    if args.restore:
        restored = restore_requirements(app_dir)
        print("restored upstream requirements.txt" if restored else "nothing to restore")
        return 0

    if args.skip_build:
        wheels = sorted(vendor_dir.glob("*.whl"))
        names = {w.name.split("-", 1)[0] for w in wheels}
        missing = [name for name, _ in PROJECTS if name not in names]
        if missing:
            raise BuildError(f"--skip-build but no wheel for {missing} in {vendor_dir}")
    else:
        wheels = build_all(root, vendor_dir, runner)
    order = {name: i for i, (name, _) in enumerate(PROJECTS)}
    wheels = sorted(wheels, key=lambda w: order.get(w.name.split("-", 1)[0], len(order)))

    lines = compose_requirements(
        upstream_requirements(app_dir).splitlines(), [w.name for w in wheels],
        with_mlflow=args.with_mlflow, wheel_hashes={w.name: sha256_file(w) for w in wheels})
    generated = write_generated(app_dir, lines)
    print(f"wrote {generated.relative_to(root)} ({len(wheels)} wheels in {vendor_dir.relative_to(root)})")
    if args.install:
        installed = install_requirements(app_dir)
        print(f"installed as {installed.relative_to(root)} (upstream copy: {UPSTREAM_COPY})")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except BuildError as exc:
        print(f"error: {exc}", file=sys.stderr)
        raise SystemExit(2)
