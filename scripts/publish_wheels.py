"""Put the kpi_evidence and reconloop wheels where a notebook can ``%pip install`` them."""
from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
import tempfile
from collections.abc import Callable, Sequence
from pathlib import Path, PureWindowsPath

try:
    ROOT = Path(__file__).resolve().parents[1]
except NameError:
    ROOT = Path.cwd()
DEFAULT_BUILD_DIR = ROOT / "build" / "notebook_wheels"
REQUIREMENTS = "requirements.txt"
MARKER = "# Generated by scripts/publish_wheels.py - do not edit."

PROJECTS: tuple[tuple[str, str], ...] = (("reconloop", "libs/reconloop"), ("kpi_evidence", "."))
DISTRIBUTIONS: tuple[str, ...] = tuple(name for name, _ in PROJECTS)

Runner = Callable[[Sequence[str]], None]


class PublishError(RuntimeError):
    """A wheel is missing, a build failed, or a folder cannot be used."""


def wheel_distribution(file_name: str) -> str | None:
    """Distribution part of a wheel file name, normalized (``kpi-evidence`` -> ``kpi_evidence``)."""
    if not file_name.endswith(".whl") or "-" not in file_name:
        return None
    return file_name.split("-", 1)[0].replace("-", "_").replace(".", "_").lower()


def find_wheels(source: Path) -> dict[str, list[Path]]:
    """Every wheel of our distributions under ``source`` (recursive), grouped by distribution."""
    found: dict[str, list[Path]] = {name: [] for name in DISTRIBUTIONS}
    for path in sorted(source.rglob("*.whl")):
        dist = wheel_distribution(path.name)
        if dist in found and path.is_file():
            found[dist].append(path)
    return found


def newest(paths: Sequence[Path]) -> Path:
    """The most recently written wheel (bundle deploy uploads each build under a new name)."""
    return max(paths, key=lambda p: (p.stat().st_mtime, p.name))


def select_wheels(source: Path) -> dict[str, Path]:
    """The wheel to publish per distribution; raises PublishError naming what was found."""
    if not source.is_dir():
        raise PublishError(f"source folder {source} does not exist (run `databricks bundle deploy` first, "
                           "or pass --source with the folder that holds the wheels)")
    found = find_wheels(source)
    missing = [name for name, paths in found.items() if not paths]
    if missing:
        listing = sorted(p.name for p in source.rglob("*.whl"))
        raise PublishError(f"no wheel for {missing} under {source}; wheels found: {listing or 'none'}")
    return {name: newest(paths) for name, paths in found.items()}


def absolute_dir(volume_dir: str) -> str:
    """The folder without a trailing slash; PublishError unless absolute."""
    base = volume_dir.rstrip("/\\")
    if not (base.startswith("/") or PureWindowsPath(base).is_absolute()):
        raise PublishError(f"--volume-dir / --dest must be an absolute path such as /Volumes/<c>/<s>/wheels, got {volume_dir!r}")
    return base


def requirements_text(volume_dir: str, wheel_names: Sequence[str]) -> str:
    """requirements.txt listing the wheels by absolute path, dependency first."""
    base = absolute_dir(volume_dir)
    lines = [MARKER, f"# Install with: %pip install -r {base}/{REQUIREMENTS}"]
    lines += [f"{base}/{name}" for name in wheel_names]
    return "\n".join(lines) + "\n"


def resolve_workspace_path(path: str) -> Path:
    """Accept workspace paths with or without the /Workspace prefix (bundle paths may omit it)."""
    candidate = Path(path)
    if candidate.exists() or not path.startswith("/") or path.startswith(("/Workspace/", "/Volumes/")):
        return candidate
    prefixed = Path("/Workspace" + path)
    return prefixed if prefixed.exists() else candidate


def _replace_file(src: Path, target: Path) -> None:
    if target.exists():
        target.unlink()
    shutil.copyfile(src, target)


def write_requirements(dest: Path, text: str) -> Path:
    """Write requirements.txt via a local temporary file, then copy it into ``dest``."""
    target = dest / REQUIREMENTS
    with tempfile.TemporaryDirectory(prefix="kpi_wheels_") as tmp:
        local = Path(tmp) / REQUIREMENTS
        local.write_text(text, encoding="utf-8")
        _replace_file(local, target)
    return target


def remove_stale(dest: Path, keep: Sequence[str]) -> list[str]:
    """Delete older wheels of our distributions from ``dest``; other files are left alone."""
    removed = []
    for path in sorted(dest.glob("*.whl")):
        if wheel_distribution(path.name) in DISTRIBUTIONS and path.name not in keep:
            path.unlink()
            removed.append(path.name)
    return removed


def copy_wheels(source: Path, dest: Path, *, volume_dir: str | None = None) -> dict[str, object]:
    """Publish the newest wheels from ``source`` into ``dest`` (order: wheels, requirements, cleanup)."""
    listed_dir = absolute_dir(volume_dir or dest.as_posix())
    selected = select_wheels(source)
    try:
        dest.mkdir(parents=True, exist_ok=True)
    except OSError as exc:
        raise PublishError(f"cannot create {dest}: {exc}") from exc
    names = []
    for dist in DISTRIBUTIONS:
        wheel = selected[dist]
        _replace_file(wheel, dest / wheel.name)
        names.append(wheel.name)
    requirements = write_requirements(dest, requirements_text(listed_dir, names))
    removed = remove_stale(dest, names)
    return {"wheels": names, "sources": [str(selected[d]) for d in DISTRIBUTIONS],
            "requirements": str(requirements), "removed": removed}


def _run(cmd: Sequence[str]) -> None:
    subprocess.run(list(cmd), check=True)


def build_command(project_dir: Path, out_dir: Path) -> list[str]:
    """uv when available (what the bundle artifacts use), else pip wheel without dependencies."""
    if shutil.which("uv"):
        return ["uv", "build", "--wheel", "--out-dir", str(out_dir), str(project_dir)]
    return [sys.executable, "-m", "pip", "wheel", "--no-deps", "-w", str(out_dir), str(project_dir)]


def _build_debris(project_dir: Path) -> set[Path]:
    found = {project_dir / "build"} if (project_dir / "build").is_dir() else set()
    for pattern in ("*.egg-info", "src/*.egg-info"):
        found |= {p for p in project_dir.glob(pattern) if p.is_dir()}
    return found


def build_wheel(project_dir: Path, dist_name: str, out_dir: Path, runner: Runner = _run, *,
                clean_debris: bool = True) -> Path:
    """Build one wheel in a fresh temporary folder and move it into ``out_dir``."""
    before = _build_debris(project_dir)
    with tempfile.TemporaryDirectory(prefix="kpi_wheel_") as tmp:
        tmp_dir = Path(tmp)
        try:
            runner(build_command(project_dir, tmp_dir))
        except (subprocess.CalledProcessError, OSError) as exc:
            raise PublishError(f"building {dist_name} in {project_dir} failed: {exc}") from exc
        finally:
            if clean_debris:
                for path in _build_debris(project_dir) - before:
                    shutil.rmtree(path, ignore_errors=True)
        wheels = sorted(p for p in tmp_dir.glob("*.whl") if wheel_distribution(p.name) == dist_name)
        if len(wheels) != 1:
            raise PublishError(f"expected one {dist_name} wheel from {project_dir}, found {[w.name for w in wheels]}")
        target = out_dir / wheels[0].name
        shutil.move(str(wheels[0]), target)
        return target


def build_all(root: Path, out_dir: Path, runner: Runner = _run) -> list[Path]:
    """Rebuild both wheels into ``out_dir``; stale wheels there are removed first."""
    out_dir.mkdir(parents=True, exist_ok=True)
    for old in out_dir.glob("*.whl"):
        old.unlink()
    return [build_wheel((root / rel).resolve(), name, out_dir, runner, clean_debris=rel != ".")
            for name, rel in PROJECTS]


def check_volume_dir(volume_dir: str) -> str:
    """A Unity Catalog volume folder (``/Volumes/<catalog>/<schema>/<volume>[/...]``), else PublishError."""
    text = volume_dir.replace("\\", "/")
    if text.startswith("/Volumes/") and len(text.strip("/").split("/")) >= 4:
        return volume_dir
    if "/Volumes/" in text and not text.startswith("/Volumes/"):
        raise PublishError(f"--volume-dir {volume_dir!r} looks rewritten by Git Bash path conversion; run with "
                           "MSYS_NO_PATHCONV=1 (or from PowerShell / cmd), e.g. "
                           "MSYS_NO_PATHCONV=1 python scripts/publish_wheels.py build --volume-dir /Volumes/<c>/<s>/<v>/wheels")
    raise PublishError(f"--volume-dir must be a volume folder like /Volumes/<catalog>/<schema>/<volume>/wheels, got {volume_dir!r}")


def upload_commands(files: Sequence[Path], volume_dir: str) -> list[str]:
    """`databricks fs cp` commands that upload ``files`` into the volume folder."""
    base = volume_dir.rstrip("/")
    return [f'databricks fs cp --overwrite "{f}" "dbfs:{base}/{f.name}"' for f in files]


def main(argv: Sequence[str] | None = None, *, runner: Runner = _run) -> int:
    """Command line: ``build`` (laptop) or ``copy`` (Databricks job task)."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = parser.add_subparsers(dest="command", required=True)
    b = sub.add_parser("build", help="build both wheels locally and write requirements.txt for a volume folder")
    b.add_argument("--volume-dir", required=True, help="volume folder the files will be uploaded to, e.g. /Volumes/main/kpi_evidence/wheels")
    b.add_argument("--out", type=Path, default=DEFAULT_BUILD_DIR, help=f"local output folder (default {DEFAULT_BUILD_DIR.relative_to(ROOT)})")
    b.add_argument("--root", type=Path, default=ROOT, help="project root (contains pyproject.toml)")
    c = sub.add_parser("copy", help="copy the newest deployed wheels into a volume folder (Databricks)")
    c.add_argument("--source", required=True, help="folder with the deployed wheels, e.g. <artifact_path>/.internal")
    c.add_argument("--dest", required=True, help="volume folder, e.g. /Volumes/<catalog>/<schema>/wheels")
    args, _unknown = parser.parse_known_args(argv)

    if args.command == "build":
        check_volume_dir(args.volume_dir)
        out_dir = args.out.resolve()
        wheels = build_all(args.root.resolve(), out_dir, runner)
        req = write_requirements(out_dir, requirements_text(args.volume_dir, [w.name for w in wheels]))
        print(f"built {len(wheels)} wheels and {req.name} in {out_dir}")
        print("upload them (or use Catalog Explorer > Upload to this volume):")
        for line in upload_commands([*wheels, req], args.volume_dir):
            print("  " + line)
        print(f"then, in a notebook:  %pip install -r {args.volume_dir.rstrip('/')}/{REQUIREMENTS}")
        return 0

    source = resolve_workspace_path(args.source)
    result = copy_wheels(source, Path(args.dest), volume_dir=args.dest)
    for wheel, src in zip(result["wheels"], result["sources"]):
        print(f"published {wheel}  (from {src})")
    print(f"wrote {result['requirements']}")
    if result["removed"]:
        print("removed older wheels: " + ", ".join(result["removed"]))
    print(f"notebooks:  %pip install -r {args.dest.rstrip('/')}/{REQUIREMENTS}")
    return 0


if __name__ == "__main__":
    try:
        exit_code = main()
    except PublishError as exc:
        print(f"error: {exc}", file=sys.stderr)
        raise SystemExit(2)
    if exit_code:
        raise SystemExit(exit_code)
